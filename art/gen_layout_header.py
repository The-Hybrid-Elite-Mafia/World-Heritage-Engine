"""Writes app/layout_gen.hpp from art/layout.py so the program and the rendered
faceplate always share the same coordinates (1920x1080 layout pixels)."""
import pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import layout as L

def r(v):
    return f"{float(v):.2f}f"

out = ["// Generated by art/gen_layout_header.py from art/layout.py — do not edit by hand.",
       "#pragma once", "", "namespace whe::ui::layout {", "",
       f"inline constexpr float W = {r(L.W)}, H = {r(L.H)};", "",
       "struct Box { float x, y, w, h; };",
       "struct KnobPos { float cx, cy, dia, ring; };", ""]
for name, (x, y, w, h, *_rest) in L.POCKETS.items():
    out.append(f"inline constexpr Box pocket_{name}{{{r(x)}, {r(y)}, {r(w)}, {r(h)}}};")
for name, (x, y, w, h, *_rest) in L.GLASS.items():
    out.append(f"inline constexpr Box glass_{name}{{{r(x)}, {r(y)}, {r(w)}, {r(h)}}};")
out.append("")
order = ["hardness", "strike", "resonance", "detune", "stiffness", "decay", "sympathetic", "release"]
out.append("// The eight knob wells routed into the plate, left to right (2 + 4 + 2).")
out.append("inline constexpr KnobPos knobWells[8] = {")
for n in order:
    cx, cy, d, ring = L.KNOBS[n]
    out.append(f"    {{{r(cx)}, {r(cy)}, {r(d)}, {r(ring)}}},  // {n}")
out.append("};")
cx, cy, d, ring = L.KNOBS["blend"]
out.append(f"inline constexpr KnobPos blendKnob{{{r(cx)}, {r(cy)}, {r(d)}, {r(ring)}}};")
cx, cy, d = L.ROUND_BUTTONS["physics"]
out.append(f"inline constexpr KnobPos physicsButton{{{r(cx)}, {r(cy)}, {r(d)}, 0.0f}};")
x, y, w, h = L.FADER
out.append(f"inline constexpr Box faderSlot{{{r(x)}, {r(y)}, {r(w)}, {r(h)}}};")
x, y, w, h = L.KEYS
out.append(f"inline constexpr Box keys{{{r(x)}, {r(y)}, {r(w)}, {r(h)}}};")
out += ["", "}  // namespace whe::ui::layout", ""]
(HERE.parent / "app" / "layout_gen.hpp").write_text("\n".join(out))
print("wrote app/layout_gen.hpp")
